/**
 * Builds the wagered-message dictionary for the Worker from SCOWL
 * (wordlist-english, size ≤ 60, English + American + British spellings).
 * Output: apps/api/src/generated/words.ts — one sorted, newline-joined string,
 * searched by binary search (no parsing cost at Worker start-up).
 * Run: npm run dict -w @gt/api
 */
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const sizes = ['10', '20', '35', '40', '50', '55', '60'];
const variants = ['english', 'american', 'british'];
const set = new Set<string>();
for (const size of sizes) {
  for (const v of variants) {
    for (const w of require(`wordlist-english/${v}-words-${size}.json`) as string[]) {
      if (/^[A-Za-z']+$/.test(w)) set.add(w.toUpperCase());
    }
  }
}
const words = [...set].sort();
const dir = new URL('../apps/api/src/generated/', import.meta.url);
mkdirSync(dir, { recursive: true });
writeFileSync(
  new URL('words.ts', dir),
  `// GENERATED by scripts/build-dictionary.ts from SCOWL (wordlist-english, MIT; word lists © Kevin Atkinson, permissive licence).\n// ${words.length} words. Do not edit.\nexport const WORDS = ${JSON.stringify(words.join('\n'))};\n`,
);
console.log(`Wrote ${words.length} words`);
